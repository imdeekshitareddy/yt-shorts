// Execution and Environment Utilities for Faceless Shorts
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

// Get default root directory for video projects: ~/faceless-shorts/ (C:\Users\<user>\faceless-shorts\)
export function getDefaultProjectsDir() {
  return path.join(os.homedir(), 'faceless-shorts');
}

// Find Git Bash binary on Windows, strictly avoiding WindowsApps WSL shim
export function findGitBashExecutable() {
  if (process.platform !== 'win32') {
    return 'bash';
  }

  const homedir = os.homedir();
  const candidates = [
    path.join(homedir, 'AppData/Local/Programs/Git/bin/bash.exe'),
    path.join(homedir, 'AppData/Local/Programs/Git/usr/bin/bash.exe'),
    'C:\\Program Files\\Git\\bin\\bash.exe',
    'C:\\Program Files\\Git\\usr\\bin\\bash.exe',
    'C:\\Program Files (x86)\\Git\\bin\\bash.exe',
    'C:\\Program Files (x86)\\Git\\usr\\bin\\bash.exe'
  ];

  for (const c of candidates) {
    if (fs.existsSync(c)) {
      return c;
    }
  }

  return null;
}

// Locate Python executable from the dedicated ~/.faceless-shorts/venv, FACELESS_PYTHON env, or system
export function findPythonExecutable() {
  if (process.env.FACELESS_PYTHON && fs.existsSync(process.env.FACELESS_PYTHON)) {
    return process.env.FACELESS_PYTHON;
  }

  const homedir = os.homedir();
  const venvPython = process.platform === 'win32'
    ? path.join(homedir, '.faceless-shorts', 'venv', 'Scripts', 'python.exe')
    : path.join(homedir, '.faceless-shorts', 'venv', 'bin', 'python');

  if (fs.existsSync(venvPython)) {
    return venvPython;
  }

  // Fallback checks for system python
  if (process.platform === 'win32') {
    // Check if py -3 or python is in path
    const pyCheck = spawnSync('py', ['-3', '-c', 'import sys; print(sys.executable)'], { encoding: 'utf8' });
    if (pyCheck.status === 0 && pyCheck.stdout?.trim()) {
      return pyCheck.stdout.trim();
    }
    const pythonCheck = spawnSync('python', ['-c', 'import sys; print(sys.executable)'], { encoding: 'utf8' });
    if (pythonCheck.status === 0 && pythonCheck.stdout?.trim()) {
      return pythonCheck.stdout.trim();
    }
  } else {
    const python3Check = spawnSync('python3', ['-c', 'import sys; print(sys.executable)'], { encoding: 'utf8' });
    if (python3Check.status === 0 && python3Check.stdout?.trim()) {
      return python3Check.stdout.trim();
    }
  }

  // Default to venv path even if not yet created (prints clear diagnostic if missing)
  return venvPython;
}

// Scaffolds a project using the original new_video.sh logic into ~/faceless-shorts/<short-name>/
// Ensures existing projects are never overwritten.
export function scaffoldProject({
  skillRoot,
  style = 'clay-world',
  name,
  parentDir = getDefaultProjectsDir()
}) {
  if (!name) {
    throw new Error('Project name/ID is required to scaffold project.');
  }

  const projectDir = path.join(parentDir, name);

  // Requirement: Never overwrite existing projects
  if (fs.existsSync(projectDir)) {
    throw new Error(
      `Project directory already exists at '${projectDir}'. ` +
      `Aborting to prevent overwriting existing project.`
    );
  }

  const newVideoScript = path.join(skillRoot, 'scripts/new_video.sh');
  const gitBash = findGitBashExecutable();
  let createdWithBash = false;

  if (gitBash && fs.existsSync(newVideoScript)) {
    try {
      const res = spawnSync(gitBash, [newVideoScript, style, name, '--dir', parentDir], {
        encoding: 'utf8'
      });
      if (res.status === 0 && fs.existsSync(projectDir)) {
        createdWithBash = true;
      }
    } catch {}
  }

  // If Bash was unavailable or failed (e.g. MSYS2 sandbox constraint on Windows),
  // execute identical steps natively in Node:
  if (!createdWithBash) {
    const src = path.join(skillRoot, 'styles', style, 'example');
    if (!fs.existsSync(src)) {
      throw new Error(`Style template not found at: ${src}`);
    }

    fs.mkdirSync(parentDir, { recursive: true });
    fs.cpSync(src, projectDir, { recursive: true });
    fs.mkdirSync(path.join(projectDir, 'renders'), { recursive: true });
    fs.mkdirSync(path.join(projectDir, 'review'), { recursive: true });
    fs.mkdirSync(path.join(projectDir, 'data'), { recursive: true });

    // Clean out sample narration and mix from template
    try {
      fs.rmSync(path.join(projectDir, 'data/narration.wav'), { force: true });
      fs.rmSync(path.join(projectDir, 'data/mix.wav'), { force: true });
    } catch {}
  }

  // Ensure ALL template timing and audio data is purged regardless of whether
  // Bash or Node created the directory. Fresh data will be generated by voice.py and words.py.
  const staleDataFiles = [
    'data/narration.wav',
    'data/mix.wav',
    'data/lines.json',
    'data/words.json',
    'data/words.txt'
  ];
  for (const rel of staleDataFiles) {
    try {
      fs.rmSync(path.join(projectDir, rel), { force: true });
    } catch {}
  }

  return projectDir;
}
